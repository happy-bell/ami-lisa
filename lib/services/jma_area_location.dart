  /// 未設定・未知コードのときの既定（岐阜県）。
  static const fallbackCode = '210000';

  /// 天気予報の地域コード（細分区域 or 府県）から府県コードを求める。
  static String toPrefCode(String area) {
    final a = area.trim();
    if (a.isEmpty) return fallbackCode;
    if (_table.containsKey(a)) return a;
    // 細分区域コード（例 210010）→ 府県コード（210000）
    if (a.length >= 6) {
      final pref = '${a.substring(0, 2)}0000';
      if (_table.containsKey(pref)) return pref;
      // 北海道・沖縄など、府県コードが特殊なものを補正
      for (final key in _table.keys) {
        if (key.substring(0, 2) == a.substring(0, 2)) return key;
      }
    }
    return fallbackCode;
  }

  static double latOf(String area) {
    final e = _table[toPrefCode(area)]!;
    return e[0] as double;
  }

  static double lonOf(String area) {
    final e = _table[toPrefCode(area)]!;
    return e[1] as double;
  }

  static String labelOf(String area) {
    final e = _table[toPrefCode(area)]!;
    return e[2] as String;
  }
